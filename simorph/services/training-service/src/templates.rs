//! Python training script templates speaking the SIMORPH protocol.

/// Which framework a template targets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TemplateKind {
    /// numpy logistic regression (runs anywhere numpy is installed).
    NumpyLogistic,
    /// PyTorch supervised fine-tuning skeleton.
    TorchSft,
    /// TRL + PEFT LoRA supervised fine-tuning skeleton.
    TrlPeftLora,
}

/// Header shared by every template: imports the bundled `simorph_adapter`
/// from `adapter_dir` (absolute path injected at generation time).
fn header(adapter_dir: &str) -> String {
    format!(
        r#"#!/usr/bin/env python3
"""Training component generated by simorph-training-service."""
import json
import os
import sys

sys.path.insert(0, {adapter_dir:?})
from simorph_adapter import Component, Manifest, Port, Request, Result, serve  # noqa: E402


def _rows(path):
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                yield json.loads(line)
"#
    )
}

/// Render a template.  `adapter_dir` is the directory containing the
/// `simorph_adapter` package.
pub fn render(kind: TemplateKind, adapter_dir: &str) -> String {
    let mut s = header(adapter_dir);
    match kind {
        TemplateKind::NumpyLogistic => s.push_str(NUMPY_LOGISTIC),
        TemplateKind::TorchSft => s.push_str(TORCH_SFT),
        TemplateKind::TrlPeftLora => s.push_str(TRL_PEFT_LORA),
    }
    s
}

const NUMPY_LOGISTIC: &str = r#"
import numpy as np  # noqa: E402


class NumpyLogisticTrainer(Component):
    """Full-batch gradient descent on rows {"inputs": {"x": [...]}, "outputs": {"y": 0/1}}."""

    def manifest(self) -> Manifest:
        return Manifest(
            name="training.numpy.logistic",
            version="1.0.0",
            provider="simorph-training-service",
            license="Apache-2.0",
            capabilities=["training"],
            supported_domains=["ai", "machine-learning"],
            inputs=[Port("dataset_path", "1", "JSON-lines dataset", shape=[0]),
                    Port("weights", "1", "initial weights", shape=[0]),
                    Port("learning_rate", "1"), Port("epochs", "1")],
            outputs=[Port("weights", "1", shape=[0]), Port("train_log_loss", "1")],
            assumptions=["binary labels in outputs.y; features in inputs.x; bias term appended"],
        )

    def execute(self, request: Request) -> Result:
        path = request.inputs["dataset_path"]
        X, y = [], []
        for r in _rows(path):
            X.append(list(r["inputs"]["x"]) + [1.0])
            y.append(float(r["outputs"]["y"]))
        X = np.asarray(X, dtype=float)
        y = np.asarray(y, dtype=float)
        w = np.asarray(request.vec("weights"), dtype=float)
        if w.size != X.shape[1]:
            raise ValueError(f"weights has {w.size} entries, expected {X.shape[1]}")
        lr = request.f("learning_rate")
        epochs = int(request.f("epochs"))
        for _ in range(epochs):
            p = 1.0 / (1.0 + np.exp(-(X @ w)))
            w -= lr * X.T @ (p - y) / len(y)
        p = np.clip(1.0 / (1.0 + np.exp(-(X @ w))), 1e-12, 1 - 1e-12)
        loss = float(-np.mean(y * np.log(p) + (1 - y) * np.log(1 - p)))
        res = Result(request, evidence="computed")
        res.output("weights", w.tolist())
        res.output("train_log_loss", loss)
        res.metric("n_rows", len(y))
        res.metric("backend_numpy", 1.0)
        return res


if __name__ == "__main__":
    serve(NumpyLogisticTrainer())
"#;

const TORCH_SFT: &str = r#"
try:
    import torch  # noqa: F401
    TORCH_AVAILABLE = True
    TORCH_ERROR = ""
except Exception as e:  # noqa: BLE001
    TORCH_AVAILABLE = False
    TORCH_ERROR = f"{type(e).__name__}: {e}"


class TorchSftTrainer(Component):
    """Supervised fine-tuning skeleton (PyTorch).  Fill `build_model` and `loss_fn`."""

    def manifest(self) -> Manifest:
        return Manifest(
            name="training.torch.sft",
            version="0.1.0",
            provider="simorph-training-service",
            license="Apache-2.0",
            capabilities=["training"],
            supported_domains=["ai", "machine-learning"],
            inputs=[Port("dataset_path", "1", "JSON-lines dataset", shape=[0]),
                    Port("checkpoint_in", "1", "path of the initial checkpoint", shape=[0]),
                    Port("learning_rate", "1"), Port("epochs", "1"), Port("batch_size", "1")],
            outputs=[Port("checkpoint_out", "1", shape=[0]), Port("train_loss", "1")],
            assumptions=["requires torch; the component reports unavailability instead of training without it"],
            dependencies=["torch"],
            security_permissions=["gpu", "write_workspace"],
        )

    def build_model(self):
        raise NotImplementedError("define the model architecture for this task")

    def loss_fn(self, model, batch):
        raise NotImplementedError("define the loss for this task")

    def execute(self, request: Request) -> Result:
        if not TORCH_AVAILABLE:
            raise RuntimeError("torch unavailable: " + TORCH_ERROR)
        import torch
        model = self.build_model()
        opt = torch.optim.AdamW(model.parameters(), lr=request.f("learning_rate"))
        rows = list(_rows(request.inputs["dataset_path"]))
        bs = int(request.f("batch_size"))
        last = float("nan")
        for _ in range(int(request.f("epochs"))):
            for i in range(0, len(rows), bs):
                opt.zero_grad()
                loss = self.loss_fn(model, rows[i:i + bs])
                loss.backward()
                opt.step()
                last = float(loss.item())
        out = os.path.join(os.getcwd(), "checkpoint_out.pt")
        torch.save(model.state_dict(), out)
        res = Result(request, evidence="computed")
        res.output("checkpoint_out", out)
        res.output("train_loss", last)
        return res


if __name__ == "__main__":
    serve(TorchSftTrainer())
"#;

const TRL_PEFT_LORA: &str = r#"
try:
    import torch  # noqa: F401
    from datasets import Dataset  # noqa: F401
    from peft import LoraConfig  # noqa: F401
    from transformers import AutoModelForCausalLM, AutoTokenizer  # noqa: F401
    from trl import SFTConfig, SFTTrainer  # noqa: F401
    STACK_AVAILABLE = True
    STACK_ERROR = ""
except Exception as e:  # noqa: BLE001
    STACK_AVAILABLE = False
    STACK_ERROR = f"{type(e).__name__}: {e}"


class LoraSftTrainer(Component):
    """TRL SFTTrainer + PEFT LoRA on a JSON-lines dataset of {"inputs": {"prompt": ...}, "outputs": {"completion": ...}}."""

    def manifest(self) -> Manifest:
        return Manifest(
            name="training.trl.lora_sft",
            version="0.1.0",
            provider="simorph-training-service",
            license="Apache-2.0",
            capabilities=["training"],
            supported_domains=["ai", "language-models"],
            inputs=[Port("dataset_path", "1", shape=[0]), Port("base_model", "1", "HF model id or local path", shape=[0]),
                    Port("lora_rank", "1"), Port("learning_rate", "1"), Port("epochs", "1")],
            outputs=[Port("adapter_dir", "1", shape=[0]), Port("train_loss", "1")],
            assumptions=["requires torch, transformers, peft, trl, datasets", "base model weights must be available locally (no network inside the sandbox)"],
            dependencies=["torch", "transformers", "peft", "trl", "datasets"],
            security_permissions=["gpu", "write_workspace"],
        )

    def execute(self, request: Request) -> Result:
        if not STACK_AVAILABLE:
            raise RuntimeError("training stack unavailable: " + STACK_ERROR)
        rows = [{"prompt": r["inputs"]["prompt"], "completion": r["outputs"]["completion"]} for r in _rows(request.inputs["dataset_path"])]
        ds = Dataset.from_list(rows)
        base = request.inputs["base_model"]
        tok = AutoTokenizer.from_pretrained(base, local_files_only=True)
        model = AutoModelForCausalLM.from_pretrained(base, local_files_only=True)
        cfg = SFTConfig(output_dir=os.path.join(os.getcwd(), "lora_out"), num_train_epochs=float(request.f("epochs")),
                        learning_rate=request.f("learning_rate"), report_to=[], logging_steps=1)
        peft_cfg = LoraConfig(r=int(request.f("lora_rank")), task_type="CAUSAL_LM")
        trainer = SFTTrainer(model=model, args=cfg, train_dataset=ds, processing_class=tok, peft_config=peft_cfg)
        out = trainer.train()
        trainer.save_model(cfg.output_dir)
        res = Result(request, evidence="computed")
        res.output("adapter_dir", cfg.output_dir)
        res.output("train_loss", float(out.training_loss))
        return res


if __name__ == "__main__":
    serve(LoraSftTrainer())
"#;
