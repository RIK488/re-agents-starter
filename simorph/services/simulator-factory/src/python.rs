//! Python component script generation (generation path b).

use simorph_core::{Port, Quantity, Result, SimorphError};
use simorph_svc_model_factory::{parse_equation, ParsedEquation};

/// Translate a SIMORPH expression into Python (`^` → `**`, `ln` → `log`).
fn to_python(expr: &str) -> String {
    expr.replace('^', "**").replace("ln(", "log(")
}

fn py_str(s: &str) -> String {
    serde_json::to_string(s).expect("string")
}

/// Emit a self-contained Python component implementing the equations with a
/// fixed-step classical RK4 scheme.  Inputs are the parameters plus
/// `<state>_0` initial conditions and `t_end`; outputs are `final_<state>`
/// and the algebraic outputs at `t_end`.
pub fn generate_python_script(
    name: &str,
    adapter_dir: &str,
    equations: &[&str],
    variables: &[Port],
    parameters: &[Quantity],
) -> Result<String> {
    let parsed: Vec<ParsedEquation> = equations
        .iter()
        .map(|e| parse_equation(e))
        .collect::<Result<_>>()?;
    let unit_of = |n: &str| {
        variables
            .iter()
            .find(|p| p.name == n)
            .map(|p| p.unit.clone())
            .ok_or_else(|| {
                SimorphError::InvalidInput(format!("variable `{n}` has no declared unit"))
            })
    };
    let mut states: Vec<(String, String, String)> = vec![];
    let mut algebraic: Vec<(String, String, String)> = vec![];
    for p in &parsed {
        match p {
            ParsedEquation::Derivative { state, expr } => {
                states.push((state.clone(), unit_of(state)?, to_python(expr)))
            }
            ParsedEquation::Algebraic { output, expr } => {
                algebraic.push((output.clone(), unit_of(output)?, to_python(expr)))
            }
        }
    }
    let mut inputs: Vec<(String, String)> = parameters
        .iter()
        .map(|q| (q.name.clone(), q.unit.clone()))
        .collect();
    for (s, u, _) in &states {
        inputs.push((format!("{s}_0"), u.clone()));
    }
    let ports_in = inputs
        .iter()
        .map(|(n, u)| format!("Port({}, {})", py_str(n), py_str(u)))
        .chain(std::iter::once("Port(\"t_end\", \"s\")".to_string()))
        .collect::<Vec<_>>()
        .join(", ");
    let ports_out = states
        .iter()
        .map(|(s, u, _)| format!("Port({}, {})", py_str(&format!("final_{s}")), py_str(u)))
        .chain(std::iter::once("Port(\"t_final\", \"s\")".to_string()))
        .chain(
            algebraic
                .iter()
                .map(|(o, u, _)| format!("Port({}, {})", py_str(o), py_str(u))),
        )
        .collect::<Vec<_>>()
        .join(", ");
    let state_names = states
        .iter()
        .map(|(s, _, _)| py_str(s))
        .collect::<Vec<_>>()
        .join(", ");
    let deriv_exprs = states
        .iter()
        .map(|(_, _, e)| py_str(e))
        .collect::<Vec<_>>()
        .join(", ");
    let alg_names = algebraic
        .iter()
        .map(|(o, _, _)| py_str(o))
        .collect::<Vec<_>>()
        .join(", ");
    let alg_exprs = algebraic
        .iter()
        .map(|(_, _, e)| py_str(e))
        .collect::<Vec<_>>()
        .join(", ");
    let param_names = inputs
        .iter()
        .map(|(n, _)| py_str(n))
        .collect::<Vec<_>>()
        .join(", ");
    let equations_doc = equations
        .iter()
        .map(|e| py_str(e))
        .collect::<Vec<_>>()
        .join(", ");
    Ok(format!(
        r#"#!/usr/bin/env python3
"""Generated by simorph-simulator-factory: {name}

Equations: [{equations_doc}]
Scheme: classical RK4, fixed step (config "dt", default t_end/2000).
"""
import math
import sys

sys.path.insert(0, {adapter})

from simorph_adapter import Component, Manifest, Port, Request, Result, serve  # noqa: E402

STATES = [{state_names}]
DERIVS = [compile(e, "<deriv>", "eval") for e in [{deriv_exprs}]]
ALG_NAMES = [{alg_names}]
ALG = [compile(e, "<alg>", "eval") for e in [{alg_exprs}]]
PARAMS = [{param_names}]
NS = {{
    "abs": abs, "sqrt": math.sqrt, "exp": math.exp, "log": math.log, "log10": math.log10,
    "sin": math.sin, "cos": math.cos, "tan": math.tan, "min": min, "max": max,
    "floor": math.floor, "ceil": math.ceil, "round": round,
    "sign": lambda v: (v > 0) - (v < 0), "pi": math.pi, "e": math.e,
}}


def rhs(t, x, p):
    ns = dict(NS)
    ns.update(p)
    ns["t"] = t
    for n, v in zip(STATES, x):
        ns[n] = v
    for n, c in zip(ALG_NAMES, ALG):
        ns[n] = eval(c, {{"__builtins__": {{}}}}, ns)
    return [eval(c, {{"__builtins__": {{}}}}, ns) for c in DERIVS]


def algebraic(t, x, p):
    ns = dict(NS)
    ns.update(p)
    ns["t"] = t
    for n, v in zip(STATES, x):
        ns[n] = v
    out = {{}}
    for n, c in zip(ALG_NAMES, ALG):
        ns[n] = eval(c, {{"__builtins__": {{}}}}, ns)
        out[n] = ns[n]
    return out


class Generated(Component):
    def manifest(self) -> Manifest:
        return Manifest(
            name={name_str},
            version="0.1.0",
            provider="simorph-simulator-factory",
            capabilities=["ode_integration"],
            inputs=[{ports_in}],
            outputs=[{ports_out}],
            assumptions=["generated from user equations; fixed-step RK4; not validated against references unless declared"],
            deterministic_mode="always",
        )

    def execute(self, request: Request) -> Result:
        p = {{n: request.f(n) for n in PARAMS}}
        t_end = request.f("t_end")
        cfg = request.config if isinstance(request.config, dict) else {{}}
        dt = float(cfg.get("dt") or (t_end / 2000.0 if t_end > 0 else 1.0))
        n = max(1, int(math.ceil(t_end / dt)))
        h = t_end / n
        x = [p[s + "_0"] for s in STATES]
        t = 0.0
        evals = 0
        for _ in range(n):
            k1 = rhs(t, x, p)
            k2 = rhs(t + h / 2, [xi + h / 2 * ki for xi, ki in zip(x, k1)], p)
            k3 = rhs(t + h / 2, [xi + h / 2 * ki for xi, ki in zip(x, k2)], p)
            k4 = rhs(t + h, [xi + h * ki for xi, ki in zip(x, k3)], p)
            x = [xi + h / 6 * (a + 2 * b + 2 * c + d) for xi, a, b, c, d in zip(x, k1, k2, k3, k4)]
            t += h
            evals += 4
            if any(not math.isfinite(v) for v in x):
                raise ValueError(f"non-finite state at t={{t}}")
        res = Result(request, evidence="simulated")
        for s, v in zip(STATES, x):
            res.output("final_" + s, v)
        res.output("t_final", t)
        for k, v in algebraic(t, x, p).items():
            res.output(k, v)
        res.metric("steps", n)
        res.metric("rhs_evals", evals)
        return res


if __name__ == "__main__":
    serve(Generated())
"#,
        name = name,
        name_str = py_str(name),
        adapter = py_str(adapter_dir),
    ))
}
