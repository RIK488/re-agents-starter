//! Proof orchestration: Z3 verdict, fresh re-run of the stored script, and
//! independent second opinions (interval branch-and-bound, LP, exhaustive
//! enumeration, native evaluation of counterexamples/witnesses).
//!
//! A certificate is `externally_checked` only when (1) the solver gave a
//! decisive answer, (2) a fresh process re-running the *stored* SMT-LIB text
//! gave the same answer, (3) at least one independent method agrees, and
//! (4) no independent method disagrees.

use crate::enumerate::{decide_feasibility, decide_proof, Enumeration};
use crate::expr::Expr;
use crate::formula::{Cmp, Problem, Sort};
use crate::interval::{check_atom_on_box, BoundCheck, Interval};
use crate::linear::{linear_difference, optimise, premises_system};
use crate::runner::solver_policy;
use crate::smt::{run_z3, SatResult};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use simorph_core::hashing::{hash_json, sha256_hex};
use simorph_core::{Result, SimorphError};
use simorph_security::SandboxPolicy;
use std::collections::BTreeMap;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Mode {
    /// Prove `premises ⇒ goal` (refutation script: assert ¬goal).
    Prove,
    /// Decide satisfiability of `premises ∧ goal`.
    Feasibility,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "verdict", rename_all = "snake_case")]
pub enum Verdict {
    Proved,
    Refuted {
        counterexample: BTreeMap<String, f64>,
        exact: BTreeMap<String, String>,
    },
    Feasible {
        witness: BTreeMap<String, f64>,
        exact: BTreeMap<String, String>,
    },
    Infeasible,
    Unknown {
        reason: String,
    },
    Timeout,
}

impl Verdict {
    pub fn is_decisive(&self) -> bool {
        !matches!(self, Verdict::Unknown { .. } | Verdict::Timeout)
    }
    fn class(&self) -> &'static str {
        match self {
            Verdict::Proved => "proved",
            Verdict::Refuted { .. } => "refuted",
            Verdict::Feasible { .. } => "feasible",
            Verdict::Infeasible => "infeasible",
            Verdict::Unknown { .. } => "unknown",
            Verdict::Timeout => "timeout",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum Agreement {
    Agrees,
    Disagrees,
    Inconclusive,
    NotApplicable,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Recheck {
    pub method: String,
    pub agreement: Agreement,
    /// Whether the method is mathematically rigorous for this problem
    /// (e.g. interval arithmetic restricted to correctly-rounded ops).
    pub rigorous: bool,
    pub details: String,
    pub elapsed_ms: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct Certificate {
    pub problem: Problem,
    pub mode: Mode,
    pub smtlib: String,
    pub smtlib_sha256: String,
    pub solver: String,
    pub solver_version: String,
    pub verdict: Verdict,
    pub solver_ms: f64,
    pub network_isolated: bool,
    /// Fresh-process re-run of the stored script.
    pub rerun_agrees: bool,
    pub rechecks: Vec<Recheck>,
    pub externally_checked: bool,
    /// An independent method contradicted the solver (investigate!).
    pub disagreement: bool,
    pub created_unix_s: u64,
}

impl Certificate {
    pub fn content_hash(&self) -> String {
        hash_json(self).expect("serialisable")
    }

    /// Detect tampering: the stored script must match its hash and must be
    /// exactly what the stored problem generates.
    pub fn verify_integrity(&self) -> Result<()> {
        if sha256_hex(self.smtlib.as_bytes()) != self.smtlib_sha256 {
            return Err(SimorphError::Protected(
                "SMT-LIB text does not match its SHA-256: certificate tampered".into(),
            ));
        }
        let regenerated = script_for(&self.problem, self.mode)?;
        if regenerated != self.smtlib {
            return Err(SimorphError::Protected(
                "stored SMT-LIB text differs from the script generated by the stored problem"
                    .into(),
            ));
        }
        Ok(())
    }

    pub fn summary(&self) -> String {
        let checks: Vec<String> = self
            .rechecks
            .iter()
            .map(|r| format!("{}={:?}", r.method, r.agreement))
            .collect();
        format!(
            "{} [{}] : {} par {} {} ({:.1} ms) ; relance {} ; contrôles indépendants : {} ; vérifié extérieurement : {}",
            self.problem.name,
            match self.mode {
                Mode::Prove => "preuve",
                Mode::Feasibility => "faisabilité",
            },
            self.verdict.class(),
            self.solver,
            self.solver_version,
            self.solver_ms,
            if self.rerun_agrees { "concordante" } else { "NON concordante" },
            checks.join(", "),
            if self.externally_checked { "oui" } else { "non" }
        )
    }
}

#[derive(Debug, Clone)]
pub struct ProveOptions {
    pub timeout_ms: u64,
    pub policy: SandboxPolicy,
    pub max_boxes: usize,
}

impl Default for ProveOptions {
    fn default() -> Self {
        Self {
            timeout_ms: 20_000,
            policy: solver_policy(),
            max_boxes: 20_000,
        }
    }
}

fn script_for(p: &Problem, mode: Mode) -> Result<String> {
    match mode {
        Mode::Prove => p.to_smtlib_refutation(),
        Mode::Feasibility => p.to_smtlib_feasibility(),
    }
}

fn verdict_from(mode: Mode, r: &SatResult) -> Verdict {
    match (mode, r) {
        (Mode::Prove, SatResult::Unsat) => Verdict::Proved,
        (Mode::Feasibility, SatResult::Unsat) => Verdict::Infeasible,
        (Mode::Prove, SatResult::Sat { model }) => Verdict::Refuted {
            counterexample: model.iter().map(|(k, v)| (k.clone(), v.approx)).collect(),
            exact: model
                .iter()
                .map(|(k, v)| (k.clone(), v.exact.clone()))
                .collect(),
        },
        (Mode::Feasibility, SatResult::Sat { model }) => Verdict::Feasible {
            witness: model.iter().map(|(k, v)| (k.clone(), v.approx)).collect(),
            exact: model
                .iter()
                .map(|(k, v)| (k.clone(), v.exact.clone()))
                .collect(),
        },
        (_, SatResult::Unknown { reason }) => Verdict::Unknown {
            reason: reason.clone(),
        },
        (_, SatResult::Timeout) => Verdict::Timeout,
    }
}

fn now_s() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

/// Prove `premises ⇒ goal`.
pub fn prove(p: &Problem, opts: &ProveOptions) -> Result<Certificate> {
    run(p, Mode::Prove, opts)
}

/// Decide feasibility of `premises ∧ goal` (goal = conjunction of constraints).
pub fn check_feasibility(p: &Problem, opts: &ProveOptions) -> Result<Certificate> {
    run(p, Mode::Feasibility, opts)
}

fn run(p: &Problem, mode: Mode, opts: &ProveOptions) -> Result<Certificate> {
    let smtlib = script_for(p, mode)?;
    let declared: Vec<String> = p.variables.iter().map(|(n, _)| n.clone()).collect();
    let first = run_z3(&smtlib, &declared, opts.timeout_ms, &opts.policy)?;
    let verdict = verdict_from(mode, &first.result);
    // fresh process re-run of the exact same text
    let second = run_z3(&smtlib, &declared, opts.timeout_ms, &opts.policy)?;
    let rerun_agrees = verdict_from(mode, &second.result).class() == verdict.class();
    let mut cert = Certificate {
        problem: p.clone(),
        mode,
        smtlib_sha256: sha256_hex(smtlib.as_bytes()),
        smtlib,
        solver: first.solver.clone(),
        solver_version: first.version.clone(),
        verdict,
        solver_ms: first.solver_ms,
        network_isolated: first.info.network_isolated,
        rerun_agrees,
        rechecks: vec![],
        externally_checked: false,
        disagreement: false,
        created_unix_s: now_s(),
    };
    if cert.verdict.is_decisive() {
        cert.rechecks = independent_checks(p, mode, &cert.verdict, opts);
    }
    finalise(&mut cert);
    Ok(cert)
}

fn finalise(cert: &mut Certificate) {
    let agrees = cert
        .rechecks
        .iter()
        .any(|r| r.agreement == Agreement::Agrees);
    cert.disagreement = cert
        .rechecks
        .iter()
        .any(|r| r.agreement == Agreement::Disagrees);
    cert.externally_checked =
        cert.verdict.is_decisive() && cert.rerun_agrees && agrees && !cert.disagreement;
}

/// Re-check a stored certificate: integrity, then a fresh solver run of the
/// stored text, then the independent methods again.
pub fn recheck(cert: &Certificate, opts: &ProveOptions) -> Result<Certificate> {
    cert.verify_integrity()?;
    let declared: Vec<String> = cert
        .problem
        .variables
        .iter()
        .map(|(n, _)| n.clone())
        .collect();
    let r = run_z3(&cert.smtlib, &declared, opts.timeout_ms, &opts.policy)?;
    let mut out = cert.clone();
    out.rerun_agrees = verdict_from(cert.mode, &r.result).class() == cert.verdict.class();
    out.rechecks = if cert.verdict.is_decisive() {
        independent_checks(&cert.problem, cert.mode, &cert.verdict, opts)
    } else {
        vec![]
    };
    finalise(&mut out);
    Ok(out)
}

fn goal_atoms(p: &Problem) -> Option<Vec<(Expr, Cmp, Expr)>> {
    p.goal.conjunct_atoms()
}

fn box_of(p: &Problem) -> Option<BTreeMap<String, Interval>> {
    let mut b = BTreeMap::new();
    for (n, s) in &p.variables {
        if *s == Sort::Bool {
            return None;
        }
        let (lo, hi) = *p.bounds.get(n)?;
        b.insert(n.clone(), Interval::new(lo, hi));
    }
    Some(b)
}

fn negate(c: Cmp) -> Option<Cmp> {
    Some(match c {
        Cmp::Le => Cmp::Gt,
        Cmp::Lt => Cmp::Ge,
        Cmp::Ge => Cmp::Lt,
        Cmp::Gt => Cmp::Le,
        Cmp::Eq => return None,
    })
}

fn timed<T>(f: impl FnOnce() -> T) -> (T, f64) {
    let t = std::time::Instant::now();
    let r = f();
    (r, t.elapsed().as_secs_f64() * 1e3)
}

fn independent_checks(
    p: &Problem,
    mode: Mode,
    verdict: &Verdict,
    opts: &ProveOptions,
) -> Vec<Recheck> {
    let mut out = vec![];
    // 1. native evaluation of counterexample / witness
    match verdict {
        Verdict::Refuted { counterexample, .. } => {
            let ((agreement, details), ms) = timed(|| {
                match (p.premises_hold(counterexample), p.goal.eval(counterexample)) {
                (Ok(true), Ok(false)) => (Agreement::Agrees, format!("contre-exemple évalué nativement : prémisses vraies, but faux en {counterexample:?}")),
                (Ok(true), Ok(true)) => (Agreement::Inconclusive, "le but est vrai au point arrondi en f64 (cas limite d'arrondi du modèle rationnel)".into()),
                (Ok(false), _) => (Agreement::Inconclusive, "le point arrondi en f64 sort des prémisses (frontière)".into()),
                (Err(e), _) | (_, Err(e)) => (Agreement::Inconclusive, format!("évaluation impossible : {e}")),
            }
            });
            out.push(Recheck {
                method: "native-evaluation".into(),
                agreement,
                rigorous: false,
                details,
                elapsed_ms: ms,
            });
        }
        Verdict::Feasible { witness, .. } => {
            let ((agreement, details), ms) =
                timed(|| match (p.premises_hold(witness), p.goal.eval(witness)) {
                    (Ok(true), Ok(true)) => (
                        Agreement::Agrees,
                        format!("témoin vérifié nativement : {witness:?}"),
                    ),
                    (Ok(a), Ok(b)) => (
                        Agreement::Inconclusive,
                        format!("témoin arrondi : prémisses {a}, contraintes {b}"),
                    ),
                    (Err(e), _) | (_, Err(e)) => (
                        Agreement::Inconclusive,
                        format!("évaluation impossible : {e}"),
                    ),
                });
            out.push(Recheck {
                method: "native-evaluation".into(),
                agreement,
                rigorous: false,
                details,
                elapsed_ms: ms,
            });
        }
        _ => {}
    }
    // 2. exhaustive enumeration (finite domains)
    if p.variables.iter().all(|(_, s)| *s != Sort::Real) {
        let (res, ms) = timed(|| match mode {
            Mode::Prove => decide_proof(p),
            Mode::Feasibility => decide_feasibility(p),
        });
        let (agreement, details) = match res {
            Ok(Enumeration::Holds { assignments, premises_satisfied }) => (if matches!(verdict, Verdict::Proved) { Agreement::Agrees } else { Agreement::Disagrees }, format!("{assignments} affectations, {premises_satisfied} satisfont les prémisses, but toujours vrai")),
            Ok(Enumeration::Violated { assignment }) => (if matches!(verdict, Verdict::Refuted { .. }) { Agreement::Agrees } else { Agreement::Disagrees }, format!("violation trouvée : {assignment:?}")),
            Ok(Enumeration::Witness { assignment }) => (if matches!(verdict, Verdict::Feasible { .. }) { Agreement::Agrees } else { Agreement::Disagrees }, format!("témoin trouvé : {assignment:?}")),
            Ok(Enumeration::NoWitness { assignments }) => (if matches!(verdict, Verdict::Infeasible) { Agreement::Agrees } else { Agreement::Disagrees }, format!("aucun témoin parmi {assignments} affectations")),
            Ok(Enumeration::NotApplicable(why)) => (Agreement::NotApplicable, why),
            Err(e) => (Agreement::Inconclusive, e.to_string()),
        };
        out.push(Recheck {
            method: "exhaustive-enumeration".into(),
            agreement,
            rigorous: agreement != Agreement::NotApplicable,
            details,
            elapsed_ms: ms,
        });
    }
    // 3. interval branch-and-bound (box-only premises)
    if p.hypotheses.is_empty() {
        if let (Some(bx), Some(atoms)) = (box_of(p), goal_atoms(p)) {
            let (r, ms) = timed(|| interval_opinion(&atoms, mode, verdict, &bx, opts.max_boxes));
            out.push(r.with_time(ms));
        }
    }
    // 4. LP (linear premises and goal)
    if let (Some(sys), Some(atoms)) = (premises_system(p), goal_atoms(p)) {
        let linear: Option<Vec<(BTreeMap<String, f64>, f64, Cmp)>> = atoms
            .iter()
            .map(|(l, c, r)| linear_difference(l, r).map(|(m, k)| (m, k, *c)))
            .collect();
        if let Some(lin) = linear {
            let (r, ms) = timed(|| lp_opinion(&sys, &lin, mode, verdict, &opts.policy));
            out.push(r.with_time(ms));
        }
    }
    out
}

trait WithTime {
    fn with_time(self, ms: f64) -> Recheck;
}
impl WithTime for Recheck {
    fn with_time(mut self, ms: f64) -> Recheck {
        self.elapsed_ms = ms;
        self
    }
}

fn interval_opinion(
    atoms: &[(Expr, Cmp, Expr)],
    mode: Mode,
    verdict: &Verdict,
    bx: &BTreeMap<String, Interval>,
    max_boxes: usize,
) -> Recheck {
    let mk = |agreement, rigorous, details: String| Recheck {
        method: "interval-branch-and-bound".into(),
        agreement,
        rigorous,
        details,
        elapsed_ms: 0.0,
    };
    let mut all_hold = true;
    let mut rigorous = true;
    let mut notes = vec![];
    let mut any_impossible = false;
    for (l, c, r) in atoms {
        let g = Expr::sub(l.clone(), r.clone());
        match check_atom_on_box(&g, *c, bx, max_boxes) {
            Ok(BoundCheck::Holds {
                boxes,
                rigorous: rg,
                worst_margin,
            }) => {
                rigorous &= rg;
                notes.push(format!(
                    "{} {:?} 0 certifié sur {boxes} boîtes (marge {worst_margin:.3e})",
                    g, c
                ));
            }
            Ok(BoundCheck::Violated { point, value }) => {
                all_hold = false;
                notes.push(format!("violation en {point:?} (valeur {value:.6e})"));
                // for feasibility: is the atom impossible everywhere?
                if mode == Mode::Feasibility {
                    if let Some(nc) = negate(*c) {
                        if let Ok(BoundCheck::Holds { rigorous: rg, .. }) =
                            check_atom_on_box(&g, nc, bx, max_boxes)
                        {
                            any_impossible = true;
                            rigorous &= rg;
                            notes.push(format!(
                                "contrainte {g} {c:?} 0 impossible sur toute la boîte"
                            ));
                        }
                    }
                }
            }
            Ok(BoundCheck::Inconclusive { boxes }) => {
                all_hold = false;
                notes.push(format!("non concluant après {boxes} boîtes"));
                if mode == Mode::Feasibility {
                    if let Some(nc) = negate(*c) {
                        if let Ok(BoundCheck::Holds { rigorous: rg, .. }) =
                            check_atom_on_box(&g, nc, bx, max_boxes)
                        {
                            any_impossible = true;
                            rigorous &= rg;
                        }
                    }
                }
            }
            Err(e) => return mk(Agreement::Inconclusive, false, e.to_string()),
        }
    }
    let details = notes.join(" ; ");
    match (mode, verdict) {
        (Mode::Prove, Verdict::Proved) => {
            if all_hold {
                mk(Agreement::Agrees, rigorous, details)
            } else if notes.iter().any(|n| n.starts_with("violation")) {
                mk(Agreement::Disagrees, rigorous, details)
            } else {
                mk(Agreement::Inconclusive, rigorous, details)
            }
        }
        (Mode::Prove, Verdict::Refuted { .. }) => {
            if notes.iter().any(|n| n.starts_with("violation")) {
                mk(Agreement::Agrees, false, details)
            } else if all_hold {
                mk(Agreement::Disagrees, rigorous, details)
            } else {
                mk(Agreement::Inconclusive, false, details)
            }
        }
        (Mode::Feasibility, Verdict::Infeasible) => {
            if any_impossible {
                mk(Agreement::Agrees, rigorous, details)
            } else {
                mk(Agreement::Inconclusive, false, details)
            }
        }
        (Mode::Feasibility, Verdict::Feasible { .. }) => {
            if any_impossible {
                mk(Agreement::Disagrees, rigorous, details)
            } else {
                mk(
                    Agreement::Inconclusive,
                    false,
                    format!("{details} (les intervalles ne prouvent pas l'existence d'un témoin)"),
                )
            }
        }
        _ => mk(Agreement::NotApplicable, false, details),
    }
}

fn lp_opinion(
    sys: &crate::linear::LinearSystem,
    lin: &[(BTreeMap<String, f64>, f64, Cmp)],
    mode: Mode,
    verdict: &Verdict,
    policy: &SandboxPolicy,
) -> Recheck {
    let mk = |agreement, details: String| Recheck {
        method: "linear-programming (scipy/HiGHS)".into(),
        agreement,
        rigorous: false,
        details,
        elapsed_ms: 0.0,
    };
    match mode {
        Mode::Prove => {
            // per atom: largest violation v (Le/Lt: max g ; Ge/Gt: −min g ; Eq: max |g|)
            let mut all_hold = true;
            let mut any_violated = false;
            let mut notes = vec![];
            for (m, k, c) in lin {
                let scale = 1.0 + k.abs() + m.values().map(|v| v.abs()).sum::<f64>();
                let tol = 1e-7 * scale;
                let v = match c {
                    Cmp::Le | Cmp::Lt => optimise(sys, m, *k, true, policy),
                    Cmp::Ge | Cmp::Gt => optimise(sys, m, *k, false, policy).map(|o| o.map(|v| -v)),
                    Cmp::Eq => match (
                        optimise(sys, m, *k, true, policy),
                        optimise(sys, m, *k, false, policy),
                    ) {
                        (Ok(Some(x)), Ok(Some(y))) => Ok(Some(x.abs().max(y.abs()))),
                        (Ok(None), _) | (_, Ok(None)) => Ok(None),
                        (Err(e), _) | (_, Err(e)) => Err(e),
                    },
                };
                match v {
                    Err(e) => return mk(Agreement::Inconclusive, e.to_string()),
                    Ok(None) => notes.push("prémisses infaisables : implication vraie".to_string()),
                    Ok(Some(v)) => {
                        notes.push(format!("violation maximale {v:.6e} (tolérance {tol:.1e})"));
                        let eq_ok = *c == Cmp::Eq && v <= tol;
                        if v > tol {
                            any_violated = true;
                            all_hold = false;
                        } else if !(v < -tol || eq_ok) {
                            all_hold = false; // borderline: within numerical tolerance
                        }
                    }
                }
            }
            let details = notes.join(" ; ");
            match verdict {
                Verdict::Proved if all_hold => mk(Agreement::Agrees, details),
                Verdict::Proved if any_violated => mk(Agreement::Disagrees, details),
                Verdict::Refuted { .. } if any_violated => mk(Agreement::Agrees, details),
                Verdict::Refuted { .. } if all_hold => mk(Agreement::Disagrees, details),
                _ => mk(
                    Agreement::Inconclusive,
                    format!("{details} (marge sous la tolérance numérique)"),
                ),
            }
        }
        Mode::Feasibility => {
            // add goal constraints to the premises and test feasibility with a zero objective
            let mut s2 = crate::linear::LinearSystem {
                vars: sys.vars.clone(),
                a_ub: sys.a_ub.clone(),
                b_ub: sys.b_ub.clone(),
                a_eq: sys.a_eq.clone(),
                b_eq: sys.b_eq.clone(),
                bounds: sys.bounds.clone(),
            };
            for (m, k, c) in lin {
                let row: Vec<f64> = s2
                    .vars
                    .iter()
                    .map(|v| m.get(v).copied().unwrap_or(0.0))
                    .collect();
                match c {
                    Cmp::Le | Cmp::Lt => {
                        s2.a_ub.push(row);
                        s2.b_ub.push(-k);
                    }
                    Cmp::Ge | Cmp::Gt => {
                        s2.a_ub.push(row.into_iter().map(|x| -x).collect());
                        s2.b_ub.push(*k);
                    }
                    Cmp::Eq => {
                        s2.a_eq.push(row);
                        s2.b_eq.push(-k);
                    }
                }
            }
            match optimise(&s2, &BTreeMap::new(), 0.0, false, policy) {
                Err(e) => mk(Agreement::Inconclusive, e.to_string()),
                Ok(None) => mk(
                    if matches!(verdict, Verdict::Infeasible) {
                        Agreement::Agrees
                    } else {
                        Agreement::Disagrees
                    },
                    "LP : système infaisable".into(),
                ),
                Ok(Some(_)) => mk(
                    if matches!(verdict, Verdict::Feasible { .. }) {
                        Agreement::Agrees
                    } else {
                        Agreement::Inconclusive
                    },
                    "LP : relaxation non stricte faisable".into(),
                ),
            }
        }
    }
}
